# Builds dist\Keystrap.exe with the .NET Framework compiler that ships with Windows.
# Usage: powershell -ExecutionPolicy Bypass -File app\build.ps1 -WebView2Dir <extracted Microsoft.Web.WebView2 package>
#        [-RuntimeCab <Microsoft.WebView2.FixedVersionRuntime.*.x64.cab>]   bundles the runtime as dist\WebView2Runtime
param([Parameter(Mandatory = $true)][string]$WebView2Dir, [string]$RuntimeCab)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

$root = Split-Path $PSScriptRoot -Parent
$dist = Join-Path $root 'dist'
New-Item -ItemType Directory -Force $dist | Out-Null
$lib = Join-Path $WebView2Dir 'lib\net462'
# 64-bit; a Fixed Version runtime used with it must be the x64 build.
$native = Join-Path $WebView2Dir 'runtimes\win-x64\native\WebView2Loader.dll'

# --- icon: the Keystrap mark (tilted square, rounded inner cut-out) as a multi-size PNG .ico ---
function New-LogoPng([int]$size) {
    $bmp = New-Object System.Drawing.Bitmap $size, $size
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = 'AntiAlias'
    $s = $size / 1024.0
    # Same geometry as the #logo symbol in keystrap.html: 768 square + 220 rounded hole, rotated 15° about the centre.
    $path = New-Object System.Drawing.Drawing2D.GraphicsPath
    $path.FillMode = 'Alternate'
    $path.AddRectangle((New-Object System.Drawing.RectangleF (128*$s), (128*$s), (768*$s), (768*$s)))
    $r = 40 * $s; $x = 402 * $s; $y = 402 * $s; $wd = 220 * $s
    $hole = New-Object System.Drawing.Drawing2D.GraphicsPath
    $hole.AddArc($x, $y, $r, $r, 180, 90); $hole.AddArc($x + $wd - $r, $y, $r, $r, 270, 90)
    $hole.AddArc($x + $wd - $r, $y + $wd - $r, $r, $r, 0, 90); $hole.AddArc($x, $y + $wd - $r, $r, $r, 90, 90)
    $hole.CloseFigure()
    $path.AddPath($hole, $false)
    $m = New-Object System.Drawing.Drawing2D.Matrix
    $m.RotateAt(15, (New-Object System.Drawing.PointF (512*$s), (512*$s)))
    $path.Transform($m)
    $brush = New-Object System.Drawing.Drawing2D.LinearGradientBrush (New-Object System.Drawing.Point 0, 0), (New-Object System.Drawing.Point 0, $size), ([System.Drawing.Color]::FromArgb(255,255,253,208)), ([System.Drawing.Color]::FromArgb(255,255,247,153))
    $g.FillPath($brush, $path)
    $g.Dispose()
    $ms = New-Object System.IO.MemoryStream
    $bmp.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png)
    $bmp.Dispose()
    , $ms.ToArray()
}
$sizes = 256, 64, 48, 32, 16
$pngs = $sizes | ForEach-Object { , (New-LogoPng $_) }
$ico = New-Object System.IO.MemoryStream
$w = New-Object System.IO.BinaryWriter $ico
$w.Write([uint16]0); $w.Write([uint16]1); $w.Write([uint16]$sizes.Count)
$offset = 6 + 16 * $sizes.Count
for ($i = 0; $i -lt $sizes.Count; $i++) {
    $d = $sizes[$i] % 256
    $w.Write([byte]$d); $w.Write([byte]$d); $w.Write([byte]0); $w.Write([byte]0)
    $w.Write([uint16]1); $w.Write([uint16]32); $w.Write([uint32]$pngs[$i].Length); $w.Write([uint32]$offset)
    $offset += $pngs[$i].Length
}
foreach ($p in $pngs) { $w.Write($p) }
$icoPath = Join-Path $PSScriptRoot 'keystrap.ico'
[System.IO.File]::WriteAllBytes($icoPath, $ico.ToArray())

# --- secrets: webhook URLs live in secrets.json (ignored by git; copy secrets.example.json) and are built in from here ---
$secretsFile = Join-Path $root 'secrets.json'
$secrets = if (Test-Path $secretsFile) { Get-Content $secretsFile -Raw -Encoding UTF8 | ConvertFrom-Json } else { Write-Warning 'No secrets.json: webhooks are off in this build.'; $null }
function Lit([string]$s) { '"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }
$secretsCs = Join-Path $PSScriptRoot 'Secrets.g.cs'
@"
// Generated by build.ps1 from secrets.json. Not in the repository; don't edit.
namespace Keystrap
{
    static class Secrets
    {
        public const string NotificationsWebhook = $(Lit $(if ($secrets) { $secrets.notificationsWebhook }));
        public const string FeedbackWebhook = $(Lit $(if ($secrets) { $secrets.feedbackWebhook }));
        public const string CrashWebhook = $(Lit $(if ($secrets) { $secrets.crashWebhook }));   // optional; empty sends crashes to NotificationsWebhook
        public const string FaqWebhook = $(Lit $(if ($secrets) { $secrets.faqWebhook }));   // optional; the "Post FAQ" button in Dev/Testing posts here
    }
}
"@ | Set-Content $secretsCs -Encoding UTF8

# --- version: version.txt ("1.0.8") is the only place it's written; tools\bump-version.ps1 moves it to the next one ---
$version = (Get-Content (Join-Path $root 'version.txt') -TotalCount 1).Trim()
if ($version -notmatch '^\d+\.\d+\.\d+$') { throw "version.txt should read like 1.0.8, not '$version'" }
$versionCs = Join-Path $PSScriptRoot 'Version.g.cs'
@"
// Generated by build.ps1 from version.txt. Not in the repository; don't edit.
using System.Reflection;

// Windows only accepts numbers here; everything shown to people uses Keystrap.Release.Version ("v$version").
[assembly: AssemblyVersion("$version.0")]
[assembly: AssemblyFileVersion("$version.0")]
[assembly: AssemblyInformationalVersion(Keystrap.Release.Version)]

namespace Keystrap
{
    static class Release
    {
        public const string Version = "v$version";
    }
}
"@ | Set-Content $versionCs -Encoding UTF8
# The page shows it too, and has to work opened straight in a browser, so its copy is kept in step here.
$htmlPath = Join-Path $root 'keystrap.html'
$html = [IO.File]::ReadAllText($htmlPath)
$stamped = $html -replace "const APP_VERSION = '[^']*';", "const APP_VERSION = 'v$version';"
if ($stamped -ne $html) { [IO.File]::WriteAllText($htmlPath, $stamped, (New-Object Text.UTF8Encoding $false)) }

# --- compile ---
$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
& $csc /nologo /target:winexe /platform:x64 /optimize+ `
    "/out:$dist\Keystrap.exe" "/win32icon:$icoPath" `
    "/resource:$root\keystrap.html,keystrap.html" `
    "/resource:$lib\Microsoft.Web.WebView2.Core.dll,lib.Microsoft.Web.WebView2.Core.dll" `
    "/resource:$lib\Microsoft.Web.WebView2.WinForms.dll,lib.Microsoft.Web.WebView2.WinForms.dll" `
    "/resource:$native,lib.WebView2Loader.dll" `
    /reference:System.Windows.Forms.dll /reference:System.Drawing.dll /reference:System.Core.dll `
    /reference:System.Net.Http.dll /reference:System.IO.Compression.dll /reference:System.IO.Compression.FileSystem.dll `
    /reference:System.Web.Extensions.dll `
    "/reference:$lib\Microsoft.Web.WebView2.Core.dll" "/reference:$lib\Microsoft.Web.WebView2.WinForms.dll" `
    "$PSScriptRoot\Program.cs" "$PSScriptRoot\WebhookService.cs" $secretsCs $versionCs
if ($LASTEXITCODE -ne 0) { throw "csc failed ($LASTEXITCODE)" }

# --- the updater: a WPF app on .NET Framework 4.8 (built into Windows), no XAML, so this compiler can build it ---
$wpf = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\WPF'
& $csc /nologo /target:winexe /platform:x64 /optimize+ `
    "/out:$dist\Keystrap.Updater.exe" "/win32icon:$icoPath" `
    "/reference:$wpf\PresentationFramework.dll" "/reference:$wpf\PresentationCore.dll" "/reference:$wpf\WindowsBase.dll" `
    /reference:System.Xaml.dll /reference:System.Core.dll /reference:System.Drawing.dll /reference:System.Net.Http.dll `
    /reference:System.IO.Compression.dll /reference:System.IO.Compression.FileSystem.dll /reference:System.Web.Extensions.dll `
    "$PSScriptRoot\Updater.cs" "$PSScriptRoot\WebhookService.cs" $secretsCs $versionCs
if ($LASTEXITCODE -ne 0) { throw "csc failed for the updater ($LASTEXITCODE)" }

Copy-Item "$lib\Microsoft.Web.WebView2.Core.dll", "$lib\Microsoft.Web.WebView2.WinForms.dll", $native $dist -Force

# --- optional: bundle a Fixed Version runtime next to the exe ---
if ($RuntimeCab) {
    $rt = Join-Path $dist 'WebView2Runtime'
    New-Item -ItemType Directory -Force $rt | Out-Null
    expand.exe $RuntimeCab -F:* $rt | Out-Null
    # WebView2's sandboxed processes need read access, or the window stays black (Microsoft's Fixed Version guidance).
    icacls $rt /grant '*S-1-15-2-1:(OI)(CI)(RX)' /grant '*S-1-15-2-2:(OI)(CI)(RX)' /T /Q | Out-Null
}
Get-ChildItem $dist | Select-Object Name, Length
